#!/bin/bash
# Round-10 Step 0 fixture suite driver. Runs every
# fixture and prints a transcript; exit code = number
# of failed fixtures. Fixtures:
#   fx_pin_guards.py      -- every hash literal pinned
#                            in run_probe.sh is 64-hex
#                            AND equals the staged
#                            file's sha256 (machine-
#                            checked, not eyeballed);
#                            the runner's seed literals
#                            equal settings_probe.json.
#   gen_search_s3.py --check
#                         -- search_s3.php regenerates
#                            byte-identically from the
#                            pinned search_s2.php; the
#                            diff is the single hook
#                            block.
#   fx_repro (reproduce_r9_tables.py)
#                         -- the Deliverable A script
#                            runs clean on the
#                            published round-9 rows;
#                            its full output is staged
#                            at fx_repro_output.txt
#                            (regenerated by the
#                            package build; the suite
#                            re-runs it and compares
#                            the SUMMARY line).
#   fx_probe_blocks.sh    -- verbatim-extraction
#                            execution of run_probe.sh's
#                            spawn/wait blocks.
#   fx_probe_python.py    -- writer/reader round trips
#                            for the probe's Python
#                            chain.
#   fx_seed_clearance.py  -- seed-family enumeration.
#   fx_runner_env.py      -- the capture environment
#                            contract (third fix pass):
#                            BLOCK:CAPTURE extracted
#                            verbatim and EXECUTED in
#                            the stub harness; the
#                            composed runner -> driver
#                            -> game environment must
#                            carry both env vars the
#                            search_s3.php uncontested
#                            hook gates on.
#   fx_label_loader.py    -- the non-finite-z chain
#                            (fourth fix pass): the
#                            job writer's strict-JSON
#                            sentinel output, the PHP
#                            label loader's load block
#                            (verbatim extraction)
#                            loading it whole, the
#                            analyzer's tail banding,
#                            and the loader's loud
#                            abort on attempt 3's real
#                            bare-Infinity line.
#   fx_eval_completeness.py
#                         -- the eval-completeness
#                            assertion (fifth fix
#                            pass): a complete
#                            synthetic jobs+evals
#                            pair passes; a deleted
#                            candidate is caught and
#                            named; a short candidate
#                            is a named count anomaly.
#   fx_probe_influence.py -- the influence read's
#                            LOGO + hold rule (fifth
#                            fix pass): a concentrated
#                            synthetic table is
#                            identified with the
#                            correct share and fires
#                            the hold line on a
#                            buildable lever; a
#                            diffuse table and a
#                            non-buildable lever do
#                            not.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
FAILED=0
run() {
  echo "===== $1 ====="
  shift
  "$@" || FAILED=$((FAILED+1))
  echo
}
run fx_pin_guards.py python3 "$HERE/fx_pin_guards.py"
run gen_search_s3.py python3 "$HERE/gen_search_s3.py" --check
run fx_probe_blocks.sh bash "$HERE/fx_probe_blocks.sh"
run fx_probe_python.py python3 "$HERE/fx_probe_python.py"
run fx_seed_clearance.py python3 "$HERE/fx_seed_clearance.py"
run fx_runner_env.py python3 "$HERE/fx_runner_env.py"
run fx_label_loader.py python3 "$HERE/fx_label_loader.py"
run fx_eval_completeness.py python3 "$HERE/fx_eval_completeness.py"
run fx_probe_influence.py python3 "$HERE/fx_probe_influence.py"
echo "===== fx_repro (summary compared with staged output) ====="
SUM_NOW=$(python3 "$HERE/../code/reproduce_r9_tables.py" 2>/dev/null \
          | grep '^==== SUMMARY' || true)
SUM_STAGED=$(grep '^==== SUMMARY' "$HERE/fx_repro_output.txt" || true)
if [ -n "$SUM_NOW" ] && [ "$SUM_NOW" = "$SUM_STAGED" ]; then
  echo "PASS fx_repro summary matches the staged output: $SUM_NOW"
else
  echo "FAIL fx_repro: now [$SUM_NOW] vs staged [$SUM_STAGED]"
  FAILED=$((FAILED+1))
fi
echo
if [ "$FAILED" = 0 ]; then echo "run_fx_r10: ALL FIXTURES PASS";
else echo "run_fx_r10: $FAILED FIXTURE(S) FAILED"; fi
exit "$FAILED"
